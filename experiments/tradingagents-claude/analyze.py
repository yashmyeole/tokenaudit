"""Write results.md from the runs in runs/.

    python experiments/tradingagents-claude/analyze.py

Prices input tokens with the rulebook's rates for the model the runs used.
Output tokens are the same in both arms and are left out of the cost.
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

from tokenaudit.counterfactual import rates
from tokenaudit.detect import diagnose
from tokenaudit.ingest import ingest_path
from tokenaudit.rulebook import load_rulebook

HERE = Path(__file__).parent
RUNS = HERE / "runs"


def run_row(path: Path, rulebook) -> dict:
    result = ingest_path(path / "trace.jsonl")
    requests = result.requests
    model = requests[0].model
    rate = rates(rulebook.lookup(model, requests[0].provider))
    total = sum(r.usage.input_total or 0 for r in requests)
    read = sum(r.usage.cache_read or 0 for r in requests)
    write = sum(r.usage.cache_creation or 0 for r in requests)
    billed = (total - read - write) + read * rate.read + write * (rate.write or 1.0)
    (diagnosis,) = diagnose(result, rulebook)
    findings = {f.detector_id: f for f in diagnosis.findings}
    unread = findings.get("unread_cache_writes")
    unread_ids = set(unread.span_ids) if unread else set()
    # an agent loops when its first block shows up in more than one request
    calls = Counter(r.blocks[0].sha256 for r in requests if r.blocks)
    premium = (rate.write or 1.0) - 1.0
    unread_all = sum(r.usage.cache_creation or 0 for r in requests if r.span_id in unread_ids)
    unread_one_off = sum(
        r.usage.cache_creation or 0
        for r in requests
        if r.span_id in unread_ids and r.blocks and calls[r.blocks[0].sha256] == 1
    )
    return {
        "run": path.name,
        "arm": "patched" if "-patched-" in path.name else "baseline",
        "config": ":".join(path.name.split("-")[2:4]) + "-" + "-".join(path.name.split("-")[4:]),
        "model": model,
        "requests": len(requests),
        "input": total,
        "read": read,
        "write": write,
        "billed": billed,
        "loops_only": billed - unread_one_off * premium,
        "no_unread": billed - unread_all * premium,
        "price": rate.price_per_mtok,
        "decision": (path / "decision.txt").read_text().strip(),
        "findings": findings,
    }


def usd(tokens: float, price: float | None) -> str:
    return f"${tokens * price / 1e6:.3f}" if price else "n/a"


def finding_cell(row: dict, detector: str) -> str:
    f = row["findings"].get(detector)
    if f is None:
        return "-"
    low = usd(f.impact.tokens_low, row["price"])
    high = usd(f.impact.tokens_high, row["price"])
    cost = high if low == high else f"{low}-{high[1:]}"
    return f"{f.severity.value} ({cost})"


def main() -> None:
    rulebook = load_rulebook()
    rows = [run_row(p, rulebook) for p in sorted(RUNS.iterdir()) if p.is_dir()]
    manifest = json.loads((RUNS / rows[0]["run"] / "manifest.json").read_text())
    lines = [
        "# Results: TradingAgents on Claude, caching off vs. on",
        "",
        f"Generated by `python experiments/tradingagents-claude/analyze.py` from `runs/`, "
        f"rulebook {rulebook.version}. Model `{rows[0]['model']}` for every agent, "
        f"TradingAgents v{manifest['versions']['tradingagents']}. Design: [README.md](README.md).",
        "",
        "Input cost is in full-price-equivalent tokens: plain input at 1x, cache reads at "
        "0.1x, cache writes at 1.25x, priced at the rulebook's input price.",
        "",
        "## Per run",
        "",
        "| Run | Arm | Requests | Input tokens | Cache reads | Cache writes | Hit rate "
        "| Input cost | Decision |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['run']} | {r['arm']} | {r['requests']} | {r['input']:,} | {r['read']:,} "
            f"| {r['write']:,} | {r['read'] / r['input']:.1%} | {usd(r['billed'], r['price'])} "
            f"| {r['decision']} |"
        )
    lines += [
        "",
        "## Baseline vs. patched, per config",
        "",
        "| Config | Baseline cost | Patched cost | Change | Loops only (estimate) | Change "
        "| No unread writes (bound) | Change |",
        "|---|---|---|---|---|---|---|---|",
    ]
    base = [r for r in rows if r["arm"] == "baseline"]
    patched = [r for r in rows if r["arm"] == "patched"]
    for b, p in zip(base, patched, strict=True):
        lines.append(
            f"| {b['config']} | {usd(b['billed'], b['price'])} | {usd(p['billed'], p['price'])} "
            f"| {p['billed'] / b['billed'] - 1:+.1%} | {usd(p['loops_only'], p['price'])} "
            f"| {p['loops_only'] / b['billed'] - 1:+.1%} | {usd(p['no_unread'], p['price'])} "
            f"| {p['no_unread'] / b['billed'] - 1:+.1%} |"
        )
    tb = sum(r["billed"] for r in base)
    tp = sum(r["billed"] for r in patched)
    tl = sum(r["loops_only"] for r in patched)
    tn = sum(r["no_unread"] for r in patched)
    price = rows[0]["price"]
    lines += [
        f"| **all** | **{usd(tb, price)}** | **{usd(tp, price)}** | **{tp / tb - 1:+.1%}** "
        f"| **{usd(tl, price)}** | **{tl / tb - 1:+.1%}** | **{usd(tn, price)}** "
        f"| **{tn / tb - 1:+.1%}** |",
        "",
        "The last four columns are computed from the patched traces, not measured. "
        "*Loops only*: agents that call once (debaters, managers, trader, single-call "
        "analysts) are sent uncached; the looping analysts keep automatic caching, so "
        "the last call of each loop still writes. *No unread writes*: every write "
        "`unread_cache_writes` flagged is priced as plain input, a bound no real policy "
        "quite reaches.",
        "",
        "## What tokenaudit reports",
        "",
        "| Run | missing_cache_markers | unread_cache_writes | misordered_shared_context |",
        "|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['run']} | {finding_cell(r, 'missing_cache_markers')} "
            f"| {finding_cell(r, 'unread_cache_writes')} "
            f"| {finding_cell(r, 'misordered_shared_context')} |"
        )
    written = sum(r["write"] for r in patched)
    read = sum(r["read"] for r in patched)
    unread = sum(
        r["findings"]["unread_cache_writes"].evidence["unread_write_tokens"]
        for r in patched
        if "unread_cache_writes" in r["findings"]
    )
    lines += [
        "",
        "## Patched arm, totals",
        "",
        f"- Cache hit rate {read / sum(r['input'] for r in patched):.1%}.",
        f"- {written / sum(r['input'] for r in patched):.0%} of input tokens were written to "
        f"the cache; {unread / written:.0%} of those writes were never read back.",
        "",
    ]
    (HERE / "results.md").write_text("\n".join(lines))
    print(f"wrote {HERE / 'results.md'}")


if __name__ == "__main__":
    main()
