"""Turn the experiment runs into results.md: the before/after evidence.

Reads every run under runs/, computes per-run cache accounting with
tokenaudit's own ingest pipeline (traced runs) or straight from the
provider's usage objects (control runs), and writes a markdown report:

- per-run table: input tokens, cached reads, hit rate, duration
- per-config baseline->patched deltas (the headline numbers)
- structural prefix stability: how many system-block hashes each arm's
  runs share with each other (the cross-run reuse the patch unlocks)
- control comparison: traced vs untraced hit rates on the same config

Run after run_experiment.sh, from the repo venv:
    python experiments/tradingagents-cache-fix/analyze.py
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path
from statistics import mean
from typing import Any

from tokenaudit.ingest import ingest_path

HERE = Path(__file__).resolve().parent
RUNS = HERE / "runs"


def traced_stats(run_dir: Path) -> dict[str, Any]:
    result = ingest_path(run_dir / "trace.jsonl")
    requests = [q for s in result.sessions for q in s.requests]
    total_input = sum(q.usage.input_total or 0 for q in requests)
    total_read = sum(q.usage.cache_read or 0 for q in requests)
    return {
        "requests": len(requests),
        "input": total_input,
        "read": total_read,
        "hit": total_read / total_input if total_input else 0.0,
        "hits_on": sum(1 for q in requests if (q.usage.cache_read or 0) > 0),
        "sys_hashes": {q.blocks[0].sha256 for q in requests if q.blocks},
    }


def control_stats(run_dir: Path) -> dict[str, Any]:
    total_input = total_read = count = 0
    for line in (run_dir / "usage.jsonl").read_text(encoding="utf-8").splitlines():
        usage = json.loads(line)["usage"]
        total_input += usage.get("prompt_tokens") or usage.get("input_tokens") or 0
        details = usage.get("prompt_tokens_details") or usage.get("input_tokens_details") or {}
        total_read += details.get("cached_tokens") or 0
        count += 1
    # An empty usage.jsonl means the tee observed nothing (its first version
    # missed the async httpx client). That is a FAILED MEASUREMENT, not a 0%
    # hit rate — rendering it as 0.0% would invent a finding.
    return {
        "requests": count,
        "input": total_input,
        "read": total_read,
        "hit": total_read / total_input if total_input else 0.0,
        "hits_on": None,
        "sys_hashes": set(),
        "measured": count > 0,
    }


def load_runs() -> list[dict[str, Any]]:
    runs = []
    for run_dir in sorted(p for p in RUNS.iterdir() if p.is_dir()):
        manifest = json.loads((run_dir / "manifest.json").read_text(encoding="utf-8"))
        control = "usage-tee" in manifest.get("observation", "")
        stats = control_stats(run_dir) if control else traced_stats(run_dir)
        runs.append(
            {
                "name": run_dir.name,
                "arm": manifest["arm"],
                "control": control,
                "config": f"{manifest['ticker']}:{manifest['trade_date']}",
                "duration_s": manifest.get("duration_s"),
                **stats,
            }
        )
    return runs


def shared_hash_stats(runs: list[dict[str, Any]], arm: str) -> str:
    """Across an arm's traced runs: fraction of system-block hashes that
    also appear in at least one *other* run of the same arm."""
    arm_runs = [r for r in runs if r["arm"] == arm and not r["control"]]
    if len(arm_runs) < 2:
        return "n/a"
    shared = total = 0
    for r in arm_runs:
        others: set[str] = set().union(*(o["sys_hashes"] for o in arm_runs if o is not r))
        total += len(r["sys_hashes"])
        shared += len(r["sys_hashes"] & others)
    return f"{shared}/{total}"


def render(runs: list[dict[str, Any]]) -> str:
    lines = [
        "# Results: cache-friendly prompt layout on TradingAgents",
        "",
        "Generated by `python experiments/tradingagents-cache-fix/analyze.py` "
        "from the runs in `runs/`. Design and honest caveats: [README.md](README.md).",
        "",
        "## Per-run accounting",
        "",
        "| Run | Arm | Config | Requests | Input tokens | Cached reads | Hit rate |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in runs:
        arm = f"{r['arm']} (control)" if r["control"] else r["arm"]
        if r["control"] and not r.get("measured", True):
            lines.append(
                f"| {r['name']} | {arm} | {r['config']} | — | — | — "
                "| no data (tee failure — rerun run_controls.sh) |"
            )
            continue
        lines.append(
            f"| {r['name']} | {arm} | {r['config']} | {r['requests']} "
            f"| {r['input']:,} | {r['read']:,} | {r['hit']:.1%} |"
        )

    by_config: dict[str, dict[str, list[dict[str, Any]]]] = defaultdict(lambda: defaultdict(list))
    for r in runs:
        if not r["control"]:
            by_config[r["config"]][r["arm"]].append(r)

    lines += [
        "",
        "## Baseline -> patched, per config",
        "",
        "| Config | Baseline hit | Patched hit | Delta | Extra cached tokens |",
        "|---|---|---|---|---|",
    ]
    deltas = []
    for config, arms in sorted(by_config.items()):
        if not arms.get("baseline") or not arms.get("patched"):
            continue
        base = arms["baseline"][0]
        patched = arms["patched"][0]
        delta = patched["hit"] - base["hit"]
        deltas.append((base, patched, delta))
        lines.append(
            f"| {config} | {base['hit']:.1%} | {patched['hit']:.1%} "
            f"| {delta * 100:+.1f} pts | {patched['read'] - base['read']:+,} |"
        )
    if deltas:
        base_mean = mean(b["hit"] for b, _, _ in deltas)
        patched_mean = mean(p["hit"] for _, p, _ in deltas)
        factor = patched_mean / base_mean if base_mean else float("inf")
        savings = mean(0.9 * (p["read"] - b["read"]) / b["input"] for b, p, _ in deltas)
        lines += [
            "",
            f"**Mean hit rate {base_mean:.1%} -> {patched_mean:.1%} "
            f"({factor:.1f}x). Mean input-bill reduction ~{savings:.1%}** "
            "(extra cached tokens x 0.9, the cached-read discount on "
            "gpt-5.4-mini, over baseline input).",
        ]

    lines += [
        "",
        "## Structural prefix stability across runs",
        "",
        "Fraction of each run's distinct first-block (system) hashes that appear "
        "byte-identical in another run of the same arm — what a provider cache "
        "could reuse across runs, measured from block digests alone:",
        "",
        f"- baseline: {shared_hash_stats(runs, 'baseline')}",
        f"- patched: {shared_hash_stats(runs, 'patched')}",
    ]

    controls = [r for r in runs if r["control"] and r.get("measured", True)]
    unmeasured = [r for r in runs if r["control"] and not r.get("measured", True)]
    traced_same = [
        r
        for r in runs
        if not r["control"]
        and r["arm"] == "baseline"
        and controls
        and r["config"] == controls[0]["config"]
    ]
    if controls and traced_same:
        traced_base = [r for r in runs if not r["control"] and r["arm"] == "baseline"]
        traced_hits = [r["hit"] for r in traced_base]
        control_hits = [r["hit"] for r in controls]
        patched_hits = [r["hit"] for r in runs if not r["control"] and r["arm"] == "patched"]
        gap = (mean(traced_hits) - mean(control_hits)) * 100
        inside = [h for h in control_hits if min(traced_hits) <= h <= max(traced_hits)]
        verdict = (
            "every untraced rate falls inside that range"
            if len(inside) == len(control_hits)
            else f"{len(inside)} of {len(control_hits)} untraced rates fall inside that range"
        )
        lines += [
            "",
            "## Control: does tracing change what we measure?",
            "",
            "The patched and baseline arms are both traced, so instrumentation "
            "cancels in the comparison — but only if it is not doing something "
            "dramatic. Untraced runs (baseline code, no OpenTelemetry, usage read "
            "passively from response bodies) test that directly:",
            "",
            "- traced baseline runs: "
            + ", ".join(f"{h:.1%}" for h in traced_hits)
            + f" (mean {mean(traced_hits):.1%})",
            "- untraced control runs, same config as run 01: "
            + ", ".join(f"{h:.1%}" for h in control_hits)
            + f" (mean {mean(control_hits):.1%})",
            "- patched runs, for scale: "
            + ", ".join(f"{h:.1%}" for h in patched_hits)
            + f" (mean {mean(patched_hits):.1%})",
            "",
            f"Traced baselines span {min(traced_hits):.1%} to {max(traced_hits):.1%}; "
            f"{verdict}. The traced-vs-untraced difference of means is "
            f"{abs(gap):.1f} points — smaller than the baseline arm's own "
            f"run-to-run spread ({(max(traced_hits) - min(traced_hits)) * 100:.1f} "
            "points across configs, and 9.3% vs 18.1% on two captures of the same "
            "config a week apart), and an order of magnitude smaller than the "
            f"patch's effect ({(mean(patched_hits) - mean(traced_hits)) * 100:+.1f} "
            "points). No untraced run comes within "
            f"{(min(patched_hits) - max(control_hits)) * 100:.0f} points of the "
            "worst patched run.",
            "",
            "So: nothing here suggests instrumentation manufactured the result, and "
            "with n=2 controls this is a consistency check, not a proof of exact "
            "neutrality.",
        ]
    elif unmeasured:
        lines += [
            "",
            "## Control: does tracing change what we measure?",
            "",
            f"**Unsupported so far**: {len(unmeasured)} control run(s) recorded no "
            "usage data (the tee failure documented in exp_runner.py), so the "
            "tracing-neutrality claim currently rests on no measurement. Rerun "
            "`run_controls.sh` and regenerate this report before citing it.",
        ]
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    runs = load_runs()
    if not runs:
        raise SystemExit(f"no runs found under {RUNS}; run run_experiment.sh first")
    report = render(runs)
    (HERE / "results.md").write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
