"""The provider caching rulebook: every constant the detectors trust.

The JSON files beside this module are the single source of truth for
provider cache behavior — minimum cacheable sizes, TTL values and their
semantics, breakpoint and lookback limits, price multipliers, accounting
shape. Detectors are worthless if these constants are folklore, so the
rulebook holds itself to three rules:

- **Every provider file carries a source URL and a verification date**, and
  a test fails CI when any entry is more than 90 days old. A rulebook that
  knows when it is rotting beats one that quietly goes stale.
- **Unknown means unknown.** Where a provider does not publish a number
  (Gemini's TTL and discount, retention and minimums for older OpenAI
  models), the field is null with a note — never a guess.
- **Provider-level defaults, model-level overrides.** A model entry only
  states what differs; the loader merges. Field *name mappings* for traces
  live in ``ingest/dialects.py``, not here, so the two can never drift.

The corpus generator reads these same files, which keeps the simulator and
the detectors on one set of constants — and the corpus regeneration test
proves any edit here against the committed fixtures.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from datetime import date
from functools import lru_cache
from importlib.resources import files
from typing import Any

RULEBOOK_VERSION = "2026.11.10"

_PROVIDER_FILES = ("anthropic.json", "openai.json", "google.json")
_PROVIDER_ALIASES = {
    "anthropic": "anthropic",
    "openai": "openai",
    "azure.ai.openai": "openai",
    "google": "google",
    "gemini": "google",
    "gcp.gemini": "google",
    "gcp.vertex_ai": "google",
}

# Model entries may override these provider-level fields.
_OVERRIDABLE = (
    "min_cacheable_tokens",
    "min_cacheable_notes",
    "max_explicit_breakpoints",
    "lookback_positions",
    "ttl",
    "ttl_semantics",
    "ttl_notes",
    "supports_explicit_cache",
    "supports_implicit_cache",
    "accounting_shape",
    "cache_read_multiplier",
    "base_input_price_per_mtok",
    "price_notes",
)

_DATE_SUFFIX = re.compile(r"-(\d{8}|\d{4}-\d{2}-\d{2}|latest)$")


class RulebookError(ValueError):
    """The rulebook data failed validation; refuse to run on bad constants."""


@dataclass(frozen=True)
class TtlOption:
    name: str
    seconds: int | None
    write_multiplier: float | None


@dataclass(frozen=True)
class ModelRules:
    """Merged, validated cache rules for one model."""

    provider: str
    model: str
    min_cacheable_tokens: int | None
    max_explicit_breakpoints: int | None
    lookback_positions: int | None
    ttl: tuple[TtlOption, ...]
    ttl_semantics: str | None
    supports_explicit_cache: bool
    supports_implicit_cache: bool
    accounting_shape: str
    cache_read_multiplier: float | None
    base_input_price_per_mtok: float | None
    source_url: str
    verified_on: date
    notes: str | None = None
    min_cacheable_notes: str | None = None
    price_notes: str | None = None


@dataclass(frozen=True)
class Rulebook:
    version: str
    models: dict[str, ModelRules]  # keyed "provider/model"

    def lookup(self, model: str | None, provider: str | None = None) -> ModelRules | None:
        """Resolve a model id, tolerating date/-latest suffixes.

        Unknown models return ``None`` — detectors must abstain rather than
        apply another model's limits.
        """
        if not model:
            return None
        base = _DATE_SUFFIX.sub("", model.lower().strip())
        if provider:
            normalized = _PROVIDER_ALIASES.get(provider.lower())
            if normalized:
                return self.models.get(f"{normalized}/{base}")
        matches = [r for key, r in self.models.items() if key.split("/", 1)[1] == base]
        return matches[0] if len(matches) == 1 else None

    def render_markdown(self) -> str:
        """The human-readable comparison table committed at docs/rulebook.md."""
        lines = [
            "# Provider caching rulebook",
            "",
            f"Version `{RULEBOOK_VERSION}`. Generated by `python -m tokenaudit rulebook` — "
            "edit the JSON files in `src/tokenaudit/rulebook/`, never this file. "
            "Every entry carries a source and a verification date; a CI test fails "
            "when any entry is more than 90 days old. `?` means the provider does "
            "not publish the number — unknown is recorded as unknown, not guessed.",
            "",
        ]
        by_provider: dict[str, list[ModelRules]] = {}
        for rules in self.models.values():
            by_provider.setdefault(rules.provider, []).append(rules)
        for provider in sorted(by_provider):
            entries = sorted(by_provider[provider], key=_table_order)
            first = entries[0]
            lines.append(f"## {provider}")
            lines.append("")
            lines.append(
                f"TTL semantics: **{first.ttl_semantics or '?'}** · accounting: "
                f"**{first.accounting_shape}** · verified {first.verified_on.isoformat()} · "
                f"[source]({first.source_url})"
            )
            if first.notes:
                lines.append("")
                lines.append(first.notes)
            lines.append("")
            lines.append(
                "| Model | Min cacheable | Breakpoints | Lookback | TTL | Read x | Write x |"
            )
            lines.append("|---|---|---|---|---|---|---|")
            for r in entries:
                ttl = (
                    ", ".join(
                        f"{t.name} ({t.seconds}s)" if t.seconds is not None else t.name
                        for t in r.ttl
                    )
                    or "?"
                )
                write = (
                    ", ".join(
                        str(t.write_multiplier) for t in r.ttl if t.write_multiplier is not None
                    )
                    or "?"
                )
                breakpoints = (
                    "?" if r.max_explicit_breakpoints is None else r.max_explicit_breakpoints
                )
                lookback = "?" if r.lookback_positions is None else r.lookback_positions
                read_mult = "?" if r.cache_read_multiplier is None else r.cache_read_multiplier
                minimum = "?" if r.min_cacheable_tokens is None else r.min_cacheable_tokens
                lines.append(
                    f"| {r.model} | {minimum} | {breakpoints} | {lookback} | "
                    f"{ttl} | {read_mult} | {write} |"
                )
            lines.append("")
        return "\n".join(lines)


def _table_order(rules: ModelRules) -> tuple[int, str]:
    # models without a published minimum sort last
    return (rules.min_cacheable_tokens or 1_000_000, rules.model)


def _merged(provider_doc: dict[str, Any], model_doc: dict[str, Any], key: str) -> Any:
    return model_doc[key] if key in model_doc else provider_doc.get(key)


def _build_model(provider_doc: dict[str, Any], model: str, model_doc: dict[str, Any]) -> ModelRules:
    provider = str(provider_doc["provider"])
    merged = {key: _merged(provider_doc, model_doc, key) for key in _OVERRIDABLE}

    min_cacheable = merged["min_cacheable_tokens"]
    min_notes = merged["min_cacheable_notes"]
    if min_cacheable is None:
        if not isinstance(min_notes, str) or not min_notes.strip():
            raise RulebookError(f"{provider}/{model}: null minimum needs min_cacheable_notes")
    elif not isinstance(min_cacheable, int) or min_cacheable <= 0:
        raise RulebookError(f"{provider}/{model}: min_cacheable_tokens must be a positive int")
    accounting = merged["accounting_shape"]
    if accounting not in ("nested", "exclusive"):
        raise RulebookError(f"{provider}/{model}: accounting_shape must be nested|exclusive")
    source_url = provider_doc.get("source_url")
    if not isinstance(source_url, str) or not source_url.startswith("https://"):
        raise RulebookError(f"{provider}/{model}: missing https source_url")
    try:
        verified = date.fromisoformat(str(provider_doc["verified_on"]))
    except (KeyError, ValueError) as exc:
        raise RulebookError(f"{provider}/{model}: missing or invalid verified_on") from exc

    ttl = tuple(
        TtlOption(
            name=str(t["name"]),
            seconds=t.get("seconds"),
            write_multiplier=t.get("write_multiplier"),
        )
        for t in (merged["ttl"] or [])
    )
    return ModelRules(
        provider=provider,
        model=model,
        min_cacheable_tokens=min_cacheable,
        max_explicit_breakpoints=merged["max_explicit_breakpoints"],
        lookback_positions=merged["lookback_positions"],
        ttl=ttl,
        ttl_semantics=merged["ttl_semantics"],
        supports_explicit_cache=bool(merged["supports_explicit_cache"]),
        supports_implicit_cache=bool(merged["supports_implicit_cache"]),
        accounting_shape=str(accounting),
        cache_read_multiplier=merged["cache_read_multiplier"],
        base_input_price_per_mtok=merged["base_input_price_per_mtok"],
        source_url=source_url,
        verified_on=verified,
        notes=provider_doc.get("notes"),
        min_cacheable_notes=min_notes,
        price_notes=merged["price_notes"],
    )


@lru_cache(maxsize=1)
def load_rulebook() -> Rulebook:
    """Load and validate the packaged rulebook; raises RulebookError on bad data."""
    models: dict[str, ModelRules] = {}
    for filename in _PROVIDER_FILES:
        doc = json.loads(files("tokenaudit.rulebook").joinpath(filename).read_text("utf-8"))
        provider = str(doc["provider"])
        for model, model_doc in doc["models"].items():
            models[f"{provider}/{model}"] = _build_model(doc, str(model), dict(model_doc))
    if not models:
        raise RulebookError("rulebook is empty")
    return Rulebook(version=RULEBOOK_VERSION, models=models)
