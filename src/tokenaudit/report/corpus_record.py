"""Per-detector corpus records, packaged from the evaluation harness.

Confidence on findings is measured, never asserted — but a probability
computed from a 16-fixture corpus would be theater. What ships instead is
the raw record ("found 3/4 planted cases, 0 false alarms in 12 negatives"),
generated by ``eval/run_eval.py`` into ``detect/corpus_record.json`` and
drift-tested, so the report can attach exactly what was measured and
nothing more.
"""

from __future__ import annotations

import json
from functools import lru_cache
from importlib.resources import files
from typing import Any


@lru_cache(maxsize=1)
def load_corpus_record() -> dict[str, dict[str, Any]]:
    text = files("tokenaudit.detect").joinpath("corpus_record.json").read_text("utf-8")
    record: dict[str, dict[str, Any]] = json.loads(text)
    return record


def describe(detector_id: str) -> str | None:
    """Human one-liner for a detector's corpus record, or None if unrecorded."""
    entry = load_corpus_record().get(detector_id)
    if entry is None:
        return None
    return (
        f"corpus record: {entry['positives_found']}/{entry['positives_total']} planted "
        f"cases found, {entry['false_alarms']} false alarms in "
        f"{entry['negatives_checked']} negatives"
    )
