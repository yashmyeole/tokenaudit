"""Evaluate every detector against the labeled corpus and publish the results.

Writes ``eval/results.md`` (human table) and ``eval/results.json`` (raw
tallies, later attached to findings as measured confidence). Both files are
committed and drift-tested, the same pattern as the corpus and the rulebook
docs: regenerating must reproduce the committed bytes, so the published
numbers can never silently disagree with the code.

Honesty framing baked into the output: these are correctness counts against
a 16-fixture corpus with known answers — a floor, not field precision. An
abstention on a fixture whose content is missing is CORRECT behavior, not a
miss, and is reported in its own column.

Run: ``python eval/run_eval.py`` (regenerates in place)
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from tokenaudit.detect.engine import DETECTORS, diagnose
from tokenaudit.ingest import ingest_path

ROOT = Path(__file__).resolve().parent.parent
FIXTURES = ROOT / "corpus" / "synthetic" / "fixtures"


def evaluate() -> dict[str, dict[str, Any]]:
    tallies: dict[str, dict[str, Any]] = {
        d.detector_id: {
            "positives_found": 0,
            "positives_missed": 0,
            "positives_abstained": 0,
            "false_alarms": 0,
            "negatives_clean": 0,
            "negatives_abstained": 0,
            "fixtures": {},
        }
        for d in DETECTORS
    }
    for label_path in sorted(FIXTURES.glob("*.label.json")):
        label = json.loads(label_path.read_text(encoding="utf-8"))
        fixture = label["fixture"]
        (diagnosis,) = diagnose(ingest_path(FIXTURES / f"{fixture}.trace.json"))
        fired = {finding.detector_id for finding in diagnosis.findings}
        for detector in DETECTORS:
            detector_id = detector.detector_id
            expected = detector_id in label["contains"]
            if detector_id in fired:
                outcome = "fired"
            elif detector_id in diagnosis.abstained:
                outcome = "abstained"
            else:
                outcome = "clean"
            tally = tallies[detector_id]
            tally["fixtures"][fixture] = {"expected": expected, "outcome": outcome}
            if expected and outcome == "fired":
                tally["positives_found"] += 1
            elif expected and outcome == "clean":
                tally["positives_missed"] += 1
            elif expected and outcome == "abstained":
                tally["positives_abstained"] += 1
            elif not expected and outcome == "fired":
                tally["false_alarms"] += 1
            elif not expected and outcome == "abstained":
                tally["negatives_abstained"] += 1
            else:
                tally["negatives_clean"] += 1
    return tallies


def render(tallies: dict[str, dict[str, Any]]) -> str:
    fixture_count = len(sorted(FIXTURES.glob("*.label.json")))
    lines = [
        "# Detector evaluation",
        "",
        f"Every detector, scored against all {fixture_count} labeled corpus fixtures "
        "(including the negative fixtures where a correct tool must stay silent, and "
        "variants with message content deliberately missing). Generated by "
        "`python eval/run_eval.py` — edit code or corpus, never this file.",
        "",
        "Read the numbers for what they are: **correctness counts against a corpus "
        "with known answers — a floor, not field precision.** The corpus is small on "
        "purpose (every case is hand-labeled and byte-reproducible), and the "
        "simulator shares assumptions with the detectors, so real-world evidence "
        "comes from the captured-runs case studies, not this table. An abstention on "
        "a fixture without captured content is correct behavior, reported in its own "
        "column — refusing to guess is part of the contract.",
        "",
        "| Detector | Positives found | Missed | False alarms | Abstained (expected / other) |",
        "|---|---|---|---|---|",
    ]
    for detector_id, tally in sorted(tallies.items()):
        lines.append(
            f"| {detector_id} | {tally['positives_found']}/"
            f"{tally['positives_found'] + tally['positives_missed'] + tally['positives_abstained']}"
            f" | {tally['positives_missed']} | {tally['false_alarms']} | "
            f"{tally['positives_abstained']} / {tally['negatives_abstained']} |"
        )
    lines += [
        "",
        "Unimplemented failure modes stay unimplemented until they have a labeled "
        "fixture: no detector ships without a measured case.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="evaluate detectors against the corpus")
    parser.add_argument("--out", type=Path, default=Path(__file__).parent)
    args = parser.parse_args()
    tallies = evaluate()
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "results.md").write_text(render(tallies), encoding="utf-8")
    (args.out / "results.json").write_text(
        json.dumps(tallies, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    total_false = sum(t["false_alarms"] for t in tallies.values())
    total_missed = sum(t["positives_missed"] for t in tallies.values())
    print(f"evaluated {len(tallies)} detectors: {total_missed} missed, {total_false} false alarms")


if __name__ == "__main__":
    main()
